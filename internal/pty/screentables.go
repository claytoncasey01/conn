package pty

import "slices"

const (
	// wideWidth is the cells a wide character takes.
	wideWidth = 2
	// asciiDelete is DEL, after the printable ASCII characters; c1End is the first character
	// after the C1 controls; combiningStart is the first combining mark, below which every
	// character from c1End is one cell.
	asciiDelete    = 0x7f
	c1End          = 0xa0
	combiningStart = 0x300
	// graphicsFirst is the first character DEC line drawing replaces, and graphicsCount how
	// many it replaces (_ to ~).
	graphicsFirst = '_'
	graphicsCount = 32
	// boundsPerRange is a range's first and last character.
	boundsPerRange = 2
)

// runeRange is the characters from first to last, inclusive.
type runeRange struct {
	first rune
	last  rune
}

// compareRange orders a range against a character, for a binary search.
func compareRange(span runeRange, char rune) int {
	if span.last < char {
		return -1
	}

	if span.first > char {
		return 1
	}

	return 0
}

